import express from "express";
import { pool } from "./db.ts";
import { crudRouter } from "./crud.ts";

export const app = express();

app.use(express.json());

app.get("/api/health", async (_req, res) => {
  const { rows } = await pool.query("SELECT NOW()");
  res.json(rows[0]);
});

// ==========================================================================
// CRUD Players
// ==========================================================================
app.use(
  "/api/players",
  crudRouter({
    table: "players",
    idColumn: "player_id",
    columns: [
      "player_id",
      "player_name",
      "age",
      "nationality",
      "team",
      "jersey_number",
      "position",
      "height_cm",
      "weight_kg",
      "preferred_foot",
      "club_name",
      "market_value_eur",
      "total_goals_tournament",
      "total_assists_tournament",
      "total_minutes_tournament",
      "player_of_match_awards",
      "tournament_rating",
    ],
    searchColumns: ["player_name", "nationality", "team", "club_name"],
    filterColumns: [
      "nationality",
      "team",
      "jersey_number",
      "position",
      "preferred_foot",
      "club_name",
    ],
    sortColumns: [
      "player_id",
      "player_name",
      "age",
      "height_cm",
      "weight_kg",
      "market_value_eur",
      "total_goals_tournament",
      "total_assists_tournament",
      "total_minutes_tournament",
      "player_of_match_awards",
      "tournament_rating",
    ],
  }),
);

// ==========================================================================
// CRUD Matches
// ==========================================================================
app.use(
  "/api/matches",
  crudRouter({
    table: "matches",
    idColumn: "match_id",
    columns: ["match_id", "match_date", "stadium", "city", "tournament_stage"],
  }),
);

